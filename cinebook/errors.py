"""Domain-specific exceptions (one place, so every layer raises/catches the same types)."""


class CineBookError(Exception): ...
class ValidationError(CineBookError): ...
class NotFoundError(CineBookError): ...
class SeatUnavailableError(CineBookError): ...
class PaymentFailedError(CineBookError): ...
class InvalidStateTransition(CineBookError): ...
class ShowStartedError(CineBookError): ...
class PermissionDenied(CineBookError): ...
class AuthenticationRequired(CineBookError): ...
class ScheduleConflictError(CineBookError): ...
class HoldExpiredError(CineBookError): ...
class TooManyAttempts(CineBookError): ...
